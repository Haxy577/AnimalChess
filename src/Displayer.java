/**
 * The {@link Displayer} should be implemented when an object has the ability
 * to display something and the display needs to be refreshed/repainted
 *
 * @author Richmond Jase Von M. Salvador
 * @version 3.0 8/2/2026
 * @since 3.0
 */
public interface Displayer {

    /**
     * Calls the object's method to repaint/refresh its display
     *
     * @since 3.0
     */
    void refresh();
}
